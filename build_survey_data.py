"""
Builds site/survey/survey-data.js for the survey page.

The question wording comes from examples/survey_forms.gs (the script that
creates the Google Forms), and the form and entry IDs from
site/survey/forms.json. Run this after changing either one.

Usage:
    python site/build_survey_data.py           # write survey-data.js
    python site/build_survey_data.py --check   # fail if survey-data.js is out of date
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
FORMS_SCRIPT = os.path.join(ROOT, "examples", "survey_forms.gs")
FORMS_JSON = os.path.join(HERE, "survey", "forms.json")
OUTPUT = os.path.join(HERE, "survey", "survey-data.js")


def _json_after(text: str, marker: str, opener: str, closer: str):
    start = text.index(opener, text.index(marker))
    depth = 0
    for i in range(start, len(text)):
        if text[i] == opener:
            depth += 1
        elif text[i] == closer:
            depth -= 1
            if depth == 0:
                return json.loads(text[start:i + 1])
    raise ValueError(f"no closing {closer} after {marker}")


def build() -> str:
    gs = open(FORMS_SCRIPT, encoding="utf-8").read()
    block = gs.split("// BEGIN QUESTIONS", 1)[1].split("// END QUESTIONS", 1)[0]
    questions = json.loads(block[block.index("["):block.rindex("]") + 1])
    pages = _json_after(gs, "const PAGES", "{", "}")
    forms = json.load(open(FORMS_JSON, encoding="utf-8"))

    for lang in ("ko", "en"):
        missing = [q["id"] for q in questions if q["id"] not in forms[lang]["entries"]]
        if missing:
            raise SystemExit(f"forms.json is missing {lang} entry IDs for: {', '.join(missing)}")

    data = {
        "questions": questions,
        "pages": pages,
        "forms": {
            lang: {
                "action": f"https://docs.google.com/forms/d/e/{forms[lang]['form_id']}/formResponse",
                "entries": forms[lang]["entries"],
            }
            for lang in ("ko", "en")
        },
        "deletionForm": f"https://docs.google.com/forms/d/e/{forms['deletion_form_id']}/viewform",
    }
    body = json.dumps(data, ensure_ascii=False, indent=1)
    return ("// Generated by site/build_survey_data.py from examples/survey_forms.gs\n"
            "// and site/survey/forms.json. Do not edit by hand.\n"
            f"window.SURVEY = {body};\n")


def main():
    content = build()
    if "--check" in sys.argv:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else ""
        if current != content:
            sys.exit("survey-data.js is out of date. Run: python site/build_survey_data.py")
        print("survey-data.js is up to date")
        return
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"wrote {os.path.relpath(OUTPUT, ROOT)}")


if __name__ == "__main__":
    main()
